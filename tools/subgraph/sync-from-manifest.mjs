#!/usr/bin/env node
/**
 * Patch subgraph.yaml and helpers.ts from deployments/<chainId>.json.
 * Does not commit network-specific patches — callers that deploy to a public
 * chain should restore the Anvil yaml/helpers afterwards (see deploy-studio.mjs).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { encodeAbiParameters, getAddress, keccak256, stringToBytes } from "viem";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const chainId = Number.parseInt(process.env.CHAIN_ID ?? "31337", 10);
const manifestPath = path.resolve(
  process.env.DEPLOYMENT_MANIFEST ?? path.join(root, "deployments", `${chainId}.json`),
);
console.log(`sync-from-manifest chainId=${chainId} file=${manifestPath}`);

if (!fs.existsSync(manifestPath)) {
  console.error(`Manifest not found: ${manifestPath}`);
  process.exit(1);
}

const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));

function graphNetworkName(id) {
  if (id === 31337) return "anvil";
  if (id === 84532) return "base-sepolia";
  return `chain-${id}`;
}

const MARKET_ID_DOMAIN = keccak256(stringToBytes("RIPTIDE.marketId.v1"));

function marketId(base, quote) {
  return keccak256(
    encodeAbiParameters(
      [{ type: "bytes32" }, { type: "address" }, { type: "address" }],
      [MARKET_ID_DOMAIN, base, quote],
    ),
  );
}

const network = graphNetworkName(chainId);
const startBlock = Math.max(1, Number(manifest.blockNumber) || 1);

const addresses = {
  aqua: getAddress(manifest.aqua),
  swapRouter: getAddress(manifest.swapRouter),
  rebalanceRouter: getAddress(manifest.rebalanceRouter),
  feeProvider: getAddress(manifest.feeProvider),
  batchExecutor: getAddress(manifest.batchExecutor),
  settler: getAddress(manifest.settler),
  quoter: getAddress(manifest.quoter),
  lens: getAddress(manifest.lens),
  baseToken: getAddress(manifest.demoTokens.base),
  quoteToken: getAddress(manifest.demoTokens.quote),
};

const demoMarket = marketId(addresses.baseToken, addresses.quoteToken);

function patchSubgraphYaml() {
  const yamlPath = path.join(root, "subgraph/subgraph.yaml");
  let yaml = fs.readFileSync(yamlPath, "utf8");

  yaml = yaml.replace(/^(\s+)network: .+$/gm, `$1network: ${network}`);
  yaml = yaml.replace(/^(\s+)startBlock: \d+/gm, `$1startBlock: ${startBlock}`);

  const replacements = [
    [/name: Aqua[\s\S]*?address: "0x[a-fA-F0-9]{40}"/, `name: Aqua\n    network: ${network}\n    source:\n      address: "${addresses.aqua}"`],
    [/name: RiptideSwapVMRouter[\s\S]*?address: "0x[a-fA-F0-9]{40}"/, `name: RiptideSwapVMRouter\n    network: ${network}\n    source:\n      address: "${addresses.swapRouter}"`],
    [/name: RiptideLvrFeeProvider[\s\S]*?address: "0x[a-fA-F0-9]{40}"/, `name: RiptideLvrFeeProvider\n    network: ${network}\n    source:\n      address: "${addresses.feeProvider}"`],
    [/name: RiptideBatchExecutor[\s\S]*?address: "0x[a-fA-F0-9]{40}"/, `name: RiptideBatchExecutor\n    network: ${network}\n    source:\n      address: "${addresses.batchExecutor}"`],
    [/name: RiptideRebalanceRouter[\s\S]*?address: "0x[a-fA-F0-9]{40}"/, `name: RiptideRebalanceRouter\n    network: ${network}\n    source:\n      address: "${addresses.rebalanceRouter}"`],
  ];

  for (const [pattern, replacement] of replacements) {
    yaml = yaml.replace(pattern, replacement);
  }

  fs.writeFileSync(yamlPath, yaml);
  console.log(`Patched ${path.relative(root, yamlPath)} network=${network} startBlock=${startBlock}`);
}

function patchHelpers() {
  const helpersPath = path.join(root, "subgraph/src/helpers.ts");
  const lower = (a) => a.toLowerCase();
  const content = `import { Address, BigInt, Bytes } from "@graphprotocol/graph-ts";

import { Protocol, Market, Maker, Token } from "../generated/schema";

// AUTO-GENERATED by tools/subgraph/sync-from-manifest.mjs — do not edit manually.
export const PROTOCOL_ID = "${chainId}";
export const DEMO_MARKET_ID = Bytes.fromHexString("${demoMarket}");
export const SWAP_ROUTER = Bytes.fromHexString("${lower(addresses.swapRouter)}");
export const SWAP_ROUTER_ADDRESS = Address.fromString("${addresses.swapRouter}");
export const BASE_TOKEN = Bytes.fromHexString("${lower(addresses.baseToken)}");
export const QUOTE_TOKEN = Bytes.fromHexString("${lower(addresses.quoteToken)}");

export function ensureProtocol(): Protocol {
  let protocol = Protocol.load(PROTOCOL_ID);
  if (protocol == null) {
    protocol = new Protocol(PROTOCOL_ID);
    protocol.chainId = BigInt.fromI32(${chainId});
    protocol.aqua = Bytes.fromHexString("${lower(addresses.aqua)}");
    protocol.swapRouter = SWAP_ROUTER;
    protocol.rebalanceRouter = Bytes.fromHexString("${lower(addresses.rebalanceRouter)}");
    protocol.batchExecutor = Bytes.fromHexString("${lower(addresses.batchExecutor)}");
    protocol.settler = Bytes.fromHexString("${lower(addresses.settler)}");
    protocol.quoter = Bytes.fromHexString("${lower(addresses.quoter)}");
    protocol.lens = Bytes.fromHexString("${lower(addresses.lens)}");
    protocol.totalFillVolume = BigInt.zero();
    protocol.totalRecapture = BigInt.zero();
    protocol.fillCount = BigInt.zero();
    protocol.rebalanceCount = BigInt.zero();
    protocol.save();
  }
  return protocol;
}

export function ensureToken(address: Bytes, symbol: string, decimals: i32): Token {
  const id = address.toHexString();
  let token = Token.load(id);
  if (token == null) {
    token = new Token(id);
    token.symbol = symbol;
    token.decimals = decimals;
    token.save();
  }
  return token;
}

export function ensureMarket(marketId: Bytes): Market {
  const id = marketId.toHexString();
  let market = Market.load(id);
  if (market == null) {
    ensureToken(BASE_TOKEN, "RBASE", 18);
    ensureToken(QUOTE_TOKEN, "RQUOTE", 18);
    market = new Market(id);
    market.baseToken = BASE_TOKEN.toHexString();
    market.quoteToken = QUOTE_TOKEN.toHexString();
    market.fillVolume = BigInt.zero();
    market.recaptureVolume = BigInt.zero();
    market.save();
  }
  return market;
}

export function ensureMaker(address: Address): Maker {
  const id = address.toHexString();
  let maker = Maker.load(id);
  if (maker == null) {
    maker = new Maker(id);
    maker.fillVolume = BigInt.zero();
    maker.recaptureVolume = BigInt.zero();
    maker.save();
  }
  return maker;
}

export function bucketStart(timestamp: BigInt): BigInt {
  const hour = BigInt.fromI32(3600);
  return timestamp.div(hour).times(hour);
}
`;
  fs.writeFileSync(helpersPath, content);
  console.log(`Patched ${path.relative(root, helpersPath)}`);
}

patchSubgraphYaml();
patchHelpers();
console.log("Subgraph synced from manifest.");
